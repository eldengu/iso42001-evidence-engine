# Single-file renderers
# --------------------------------------------------------------------------- #


def _embed_json(payload: dict[str, Any]) -> str:
    """JSON that is safe to inline inside <script> / JSX (no raw '</' or U+2028/9)."""
    text = json.dumps(payload, indent=2, ensure_ascii=False)
    return (
        text.replace("</", "<\\/")
        .replace("\u2028", "\\u2028")
        .replace("\u2029", "\\u2029")
    )


def render_react_component(payload: dict[str, Any]) -> str:
    """
    Return a self-contained React (JSX) component string.

    The payload is embedded as a constant so the component has no network
    dependency; it is suitable for direct use as a Claude Artifact.
    """
    data = _embed_json(payload)
    return f"""import React from "react";

/** Generated by iso42001-evidence-engine - Zero-Trust ISO/IEC 42001 dashboard. */
const PAYLOAD = {data};

const STATUS_STYLE = {{
  PASS: {{ bg: "#e6f4ea", fg: "#137333", label: "Pass" }},
  NEEDS_REVIEW: {{ bg: "#fef7e0", fg: "#b06000", label: "Needs review" }},
  FAIL: {{ bg: "#fce8e6", fg: "#c5221f", label: "Fail" }},
}};

function Badge({{ status }}) {{
  const s = STATUS_STYLE[status] ?? STATUS_STYLE.NEEDS_REVIEW;
  return (
    <span style={{{{ background: s.bg, color: s.fg, padding: "2px 10px", borderRadius: 999, fontSize: 12, fontWeight: 600 }}}}>
      {{s.label}}
    </span>
  );
}}

function Stat({{ label, value }}) {{
  return (
    <div style={{{{ flex: 1, minWidth: 140, padding: 16, borderRadius: 12, background: "var(--card, #f6f8fa)" }}}}>
      <div style={{{{ fontSize: 12, opacity: 0.7 }}}}>{{label}}</div>
      <div style={{{{ fontSize: 28, fontWeight: 700 }}}}>{{value}}</div>
    </div>
  );
}}

export default function Iso42001Dashboard() {{
  const p = PAYLOAD;
  const cards = p.visualization?.control_cards ?? [];
  return (
    <div style={{{{ fontFamily: "system-ui, sans-serif", padding: 24, maxWidth: 960, margin: "0 auto" }}}}>
      <h1 style={{{{ margin: 0 }}}}>ISO/IEC 42001 Zero-Trust Evidence</h1>
      <p style={{{{ opacity: 0.7, marginTop: 4 }}}}>
        {{p.system_name}} &middot; generated {{p.generated_at}} &middot; schema v{{p.schema_version}}
      </p>
      <div style={{{{ display: "flex", gap: 12, flexWrap: "wrap", margin: "20px 0" }}}}>
        <Stat label="Compliance score" value={{`${{p.overall_compliance_score}}%`}} />
        <Stat label="Controls tested" value={{p.total_controls_tested}} />
        <Stat label="Passed" value={{p.passed_controls}} />
        <Stat label="Needs review" value={{p.needs_review_controls}} />
        <Stat label="Failed" value={{p.failed_controls}} />
      </div>
      <table style={{{{ width: "100%", borderCollapse: "collapse", fontSize: 14 }}}}>
        <thead>
          <tr style={{{{ textAlign: "left", borderBottom: "1px solid #ddd" }}}}>
            <th style={{{{ padding: 8 }}}}>Control</th>
            <th style={{{{ padding: 8 }}}}>NIST AI RMF</th>
            <th style={{{{ padding: 8 }}}}>Status</th>
            <th style={{{{ padding: 8 }}}}>Summary</th>
            <th style={{{{ padding: 8 }}}}>Signature</th>
          </tr>
        </thead>
        <tbody>
          {{cards.map((c) => (
            <tr key={{c.control_id}} style={{{{ borderBottom: "1px solid #eee", verticalAlign: "top" }}}}>
              <td style={{{{ padding: 8 }}}}><strong>{{c.control_id}}</strong><br /><span style={{{{ opacity: 0.7 }}}}>{{c.title}}</span></td>
              <td style={{{{ padding: 8 }}}}>{{c.nist_ai_rmf_function}}</td>
              <td style={{{{ padding: 8 }}}}><Badge status={{c.status}} /></td>
              <td style={{{{ padding: 8 }}}}>{{c.summary}}</td>
              <td style={{{{ padding: 8, fontFamily: "monospace", fontSize: 12 }}}}>{{c.signature_prefix}}&hellip;</td>
            </tr>
          ))}}
        </tbody>
      </table>
      <p style={{{{ fontSize: 12, opacity: 0.6, marginTop: 20 }}}}>
        Proofs are HMAC-SHA256 signed over SHA-256 evidence digests. No raw data is included.
      </p>
    </div>
  );
}}
"""


