"""
Claude Dashboard (Artifact) exporter.

Converts a list of signed ``ZeroTrustProof`` objects into:

* a JSON-serialisable ``dict`` (``export_claude_artifact``) validated through
  :class:`~.schemas.ClaudeDashboardArtifactPayload`;
* a single-file React component string (``render_react_component``) that
  embeds the payload and can be pasted directly into a Claude Artifact;
* a single-file, dependency-free HTML dashboard (``render_html_dashboard``).

None of the exporters touch raw data: they only re-shape proofs that already
contain nothing but digests, statuses and summaries.
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from datetime import datetime, timezone
from typing import Any

from .evaluator import ZeroTrustEvaluator
from .schemas import ClaudeDashboardArtifactPayload, ControlStatus, ZeroTrustProof

_STATUS_ORDER: tuple[ControlStatus, ...] = (
    ControlStatus.PASS,
    ControlStatus.NEEDS_REVIEW,
    ControlStatus.FAIL,
)

_INTEGRITY_BLOCK: dict[str, str] = {
    "evidence_hash_algorithm": "SHA-256",
    "signature_algorithm": "HMAC-SHA256",
    "key_derivation": "HKDF-SHA256",
    "signed_fields": "all proof fields except `signature`, canonical JSON (sorted keys)",
    "data_residency": "local-only; proofs contain digests, statuses and summaries only",
}


def build_payload_model(
    system_name: str, proofs: Iterable[ZeroTrustProof]
) -> ClaudeDashboardArtifactPayload:
    """Validate inputs and assemble the typed dashboard payload."""
    if not isinstance(system_name, str) or not system_name.strip():
        raise ValueError("system_name must be a non-empty string.")

    proof_list = list(proofs)
    for proof in proof_list:
        if not isinstance(proof, ZeroTrustProof):
            raise TypeError("every proof must be a ZeroTrustProof instance.")

    counts = {status: 0 for status in ControlStatus}
    for proof in proof_list:
        counts[proof.status] += 1

    return ClaudeDashboardArtifactPayload(
        generated_at=datetime.now(timezone.utc),
        system_name=system_name.strip(),
        overall_compliance_score=ZeroTrustEvaluator.compute_overall_score(proof_list),
        total_controls_tested=len(proof_list),
        passed_controls=counts[ControlStatus.PASS],
        failed_controls=counts[ControlStatus.FAIL],
        needs_review_controls=counts[ControlStatus.NEEDS_REVIEW],
        proofs=proof_list,
    )


def export_claude_artifact(system_name: str, proofs: Iterable[ZeroTrustProof]) -> dict[str, Any]:
    """
    Build a JSON-ready dict for a Claude Dashboard / Artifact.

    The top-level keys mirror :class:`ClaudeDashboardArtifactPayload`. Two
    extra, purely presentational sections are appended:

    * ``visualization`` - pre-aggregated series for charts and control cards.
    * ``integrity`` - a human-readable description of the signing scheme.
    """
    model = build_payload_model(system_name, proofs)
    payload: dict[str, Any] = model.model_dump(mode="json")

    payload["visualization"] = {
        "status_distribution": [
            {
                "status": status.value,
                "count": sum(1 for p in model.proofs if p.status is status),
            }
            for status in _STATUS_ORDER
        ],
        "control_cards": [
            {
                "control_id": p.control_id.value,
                "title": p.control_id.title,
                "nist_ai_rmf_function": p.control_id.nist_ai_rmf_function,
                "status": p.status.value,
                "asl_level": p.asl_level.value,
                "summary": p.summary,
                "evidence_hash_prefix": p.evidence_hash[:16],
                "signature_prefix": p.signature[:16],
            }
            for p in model.proofs
        ],
    }
    payload["integrity"] = dict(_INTEGRITY_BLOCK)
    return payload


